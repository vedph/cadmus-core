using Microsoft.EntityFrameworkCore;

namespace Cadmus.Graph.Ef;

public abstract partial class EfGraphRepository
{
    #region Graph Set
    private static IQueryable<EfNode> WhereSidStartsWith(
        IQueryable<EfNode> nodes, string prefix) =>
        nodes.Where(n => n.Sid != null && n.Sid.ToLower().StartsWith(prefix));

    private static IQueryable<EfTriple> WhereSidStartsWith(
        IQueryable<EfTriple> triples, string prefix) =>
        triples.Where(t => t.Sid != null && t.Sid.ToLower().StartsWith(prefix));

    /// <summary>
    /// Gets the set of graph's nodes and triples whose SID starts with
    /// the specified GUID. This identifies all the nodes and triples
    /// generated from a single source item or part.
    /// </summary>
    /// <param name="sourceId">The source identifier.</param>
    /// <param name="cancel">The cancellation token.</param>
    /// <returns>The set.</returns>
    /// <exception cref="ArgumentNullException">sourceId</exception>
    public async Task<GraphSet> GetGraphSetAsync(string sourceId,
        CancellationToken cancel = default)
    {
        ArgumentNullException.ThrowIfNull(sourceId);

        await using CadmusGraphDbContext context = GetContext();
        string prefix = sourceId.ToLowerInvariant();

        List<EfNode> nodes = await WhereSidStartsWith(
            context.Nodes.AsNoTracking().Include(n => n.UriEntry), prefix)
            .OrderBy(n => n.Id)
            .ToListAsync(cancel);

        List<EfTriple> triples = await WhereSidStartsWith(context.Triples
            .AsNoTracking()
            .Include(t => t.Subject).ThenInclude(n => n!.UriEntry)
            .Include(t => t.Predicate).ThenInclude(n => n!.UriEntry)
            .Include(t => t.Object).ThenInclude(n => n!.UriEntry), prefix)
            .OrderBy(t => t.Id)
            .ToListAsync(cancel);

        return new GraphSet(
            nodes.ConvertAll(n => n.ToUriNode()),
            triples.ConvertAll(t => t.ToUriTriple()));
    }

    /// <summary>
    /// Gets the set of graph's nodes and triples whose SID starts with
    /// the specified GUID (see <see cref="GetGraphSetAsync"/>).
    /// </summary>
    /// <param name="sourceId">The source identifier.</param>
    /// <returns>The set.</returns>
    /// <exception cref="ArgumentNullException">sourceId</exception>
    public GraphSet GetGraphSet(string sourceId) =>
        GetGraphSetAsync(sourceId).GetAwaiter().GetResult();

    /// <summary>
    /// Releases the specified nodes, which are no longer generated by
    /// the source with the specified SID prefix:
    /// <list type="bullet">
    /// <item><description>nodes no longer used by any triple are deleted,
    /// unless they are classes or properties;</description></item>
    /// <item><description>nodes still used by triples of the same source
    /// are kept as they are;</description></item>
    /// <item><description>nodes still used only by triples of other sources
    /// (or by user-created triples) are handed over to the source of one of
    /// them, as implicit nodes, so that they get removed when no longer used
    /// (or never, when used by users).</description></item>
    /// </list>
    /// This ensures that deleting a node never deletes in cascade the
    /// triples of other sources or users using it.
    /// </summary>
    private static async Task ReleaseNodesAsync(CadmusGraphDbContext context,
        IList<EfNode> nodes, string prefix, CancellationToken cancel)
    {
        if (nodes.Count == 0) return;

        List<int> ids = [.. nodes.Select(n => n.Id)];
        HashSet<int> properties = [.. await context.Properties.AsNoTracking()
            .Where(p => ids.Contains(p.Id))
            .Select(p => p.Id)
            .ToListAsync(cancel)];

        // find the triples still using the nodes
        var refs = await context.Triples.AsNoTracking()
            .Where(t => ids.Contains(t.SubjectId) ||
                ids.Contains(t.PredicateId) ||
                (t.ObjectId != null && ids.Contains(t.ObjectId.Value)))
            .Select(t => new { t.SubjectId, t.PredicateId, t.ObjectId, t.Sid })
            .ToListAsync(cancel);

        Dictionary<int, List<string?>> sidsByNode = [];
        foreach (var r in refs)
        {
            foreach (int id in new[] { r.SubjectId, r.PredicateId,
                r.ObjectId ?? 0 })
            {
                if (id == 0) continue;
                if (!sidsByNode.TryGetValue(id, out List<string?>? sids))
                    sidsByNode[id] = sids = [];
                sids.Add(r.Sid);
            }
        }

        foreach (EfNode node in nodes)
        {
            if (!sidsByNode.TryGetValue(node.Id, out List<string?>? sids))
            {
                // no longer used: delete it, unless it's a class or property
                if (!node.IsClass && !properties.Contains(node.Id) &&
                    !string.Equals(node.Tag, Node.TAG_PROPERTY,
                        StringComparison.OrdinalIgnoreCase))
                {
                    context.Nodes.Remove(node);
                }
                continue;
            }

            // still used by the same source: keep it
            if (sids.Any(s => s?.StartsWith(prefix,
                StringComparison.OrdinalIgnoreCase) == true))
            {
                continue;
            }

            // used only by others: hand it over
            node.Sid = sids.Where(s => s != null)
                .Order(StringComparer.Ordinal)
                .FirstOrDefault();
            node.SourceType = Node.SOURCE_IMPLICIT;
        }
        await context.SaveChangesAsync(cancel);
    }

    /// <summary>
    /// Deletes the set of graph's nodes and triples whose SID starts with
    /// the specified GUID. This identifies all the nodes and triples
    /// generated from a single source item or part. All the triples are
    /// deleted, while nodes are deleted only when they are no longer used
    /// by other triples, and are not classes or properties.
    /// </summary>
    /// <param name="sourceId">The source identifier.</param>
    /// <param name="cancel">The cancellation token.</param>
    /// <exception cref="ArgumentNullException">sourceId</exception>
    public async Task DeleteGraphSetAsync(string sourceId,
        CancellationToken cancel = default)
    {
        ArgumentNullException.ThrowIfNull(sourceId);
        if (sourceId.Length == 0) return;

        await using CadmusGraphDbContext context = GetContext();
        await RunInTransactionAsync(context, async () =>
        {
            await LockAsync(context, LOCK_SOURCE,
                [GraphSet.GetSourceGuid(sourceId)], cancel);
            string prefix = sourceId.ToLowerInvariant();
            (int aId, int subId) = await GetASubIdsAsync(context, cancel);
            ClassChanges changes = new();

            // triples
            List<EfTriple> triples = await WhereSidStartsWith(
                context.Triples, prefix).ToListAsync(cancel);
            foreach (EfTriple triple in triples) changes.Add(triple, aId, subId);
            context.Triples.RemoveRange(triples);
            await context.SaveChangesAsync(cancel);

            // nodes
            List<EfNode> nodes = await WhereSidStartsWith(
                context.Nodes, prefix).ToListAsync(cancel);
            await ReleaseNodesAsync(context, nodes, prefix, cancel);

            await UpdateClassesAsync(context, changes, aId, subId, cancel);
        }, cancel);
    }

    /// <summary>
    /// Deletes the set of graph's nodes and triples whose SID starts with
    /// the specified GUID (see <see cref="DeleteGraphSetAsync"/>).
    /// </summary>
    /// <param name="sourceId">The source identifier.</param>
    /// <exception cref="ArgumentNullException">sourceId</exception>
    public void DeleteGraphSet(string sourceId) =>
        DeleteGraphSetAsync(sourceId).GetAwaiter().GetResult();
    #endregion

    #region Update Graph
    /// <summary>
    /// The identity of a triple generated from a source: triples with the
    /// same identity are the same triple, whose other properties (like the
    /// tag) can be updated.
    /// </summary>
    private sealed record TripleKey(int S, int P, int O, string? Literal,
        string? Type, string? Language, string Sid);

    private static TripleKey GetKey(Triple t) => new(
        t.SubjectId, t.PredicateId, t.ObjectId ?? 0,
        t.ObjectId is null or 0 ? t.ObjectLiteral : null,
        t.LiteralType, t.LiteralLanguage,
        (t.Sid ?? "").ToLowerInvariant());

    /// <summary>
    /// Normalizes the set, resolving URIs into IDs, and truncating values
    /// longer than their columns (deterministically, so that each update
    /// produces the same values).
    /// </summary>
    private async Task ResolveSetAsync(CadmusGraphDbContext context,
        GraphSet set, CancellationToken cancel)
    {
        List<string> uris = [];

        foreach (UriNode node in set.Nodes)
        {
            if (node.Id == 0)
            {
                if (string.IsNullOrEmpty(node.Uri))
                {
                    throw new CadmusGraphException(
                        $"Node without ID nor URI: {node}");
                }
                uris.Add(node.Uri);
            }
            node.Label = Truncate(node.Label, MAX_LABEL);
            node.Tag = Truncate(node.Tag, MAX_TAG);
            node.Sid = Truncate(node.Sid, MAX_SID);
        }

        foreach (UriTriple triple in set.Triples)
        {
            if (triple.SubjectId == 0)
            {
                if (string.IsNullOrEmpty(triple.SubjectUri))
                {
                    throw new CadmusGraphException(
                        $"Triple without subject: {triple}");
                }
                uris.Add(triple.SubjectUri);
            }
            if (triple.PredicateId == 0)
            {
                if (string.IsNullOrEmpty(triple.PredicateUri))
                {
                    throw new CadmusGraphException(
                        $"Triple without predicate: {triple}");
                }
                uris.Add(triple.PredicateUri);
            }
            if (triple.ObjectId is null or 0)
            {
                triple.ObjectId = null;
                if (!string.IsNullOrEmpty(triple.ObjectUri))
                    uris.Add(triple.ObjectUri);
                else if (triple.ObjectLiteral == null)
                {
                    throw new CadmusGraphException(
                        $"Triple without object: {triple}");
                }
            }
            triple.Sid = Truncate(triple.Sid, MAX_SID);
            triple.Tag = Truncate(triple.Tag, MAX_TAG);
            triple.LiteralType = Truncate(triple.LiteralType, MAX_LIT_TYPE);
            triple.LiteralLanguage = Truncate(triple.LiteralLanguage,
                MAX_LIT_LANG);
            triple.ObjectLiteralIx = Truncate(triple.ObjectLiteralIx,
                MAX_LIT_IX);
        }

        if (uris.Count == 0) return;

        // resolve all the URIs at once
        Dictionary<string, int> ids = await ResolveUrisAsync(context, uris,
            cancel);
        foreach (UriNode node in set.Nodes.Where(n => n.Id == 0))
            node.Id = ids[node.Uri!];

        foreach (UriTriple triple in set.Triples)
        {
            if (triple.SubjectId == 0) triple.SubjectId = ids[triple.SubjectUri!];
            if (triple.PredicateId == 0)
                triple.PredicateId = ids[triple.PredicateUri!];
            if (triple.ObjectId == null && !string.IsNullOrEmpty(triple.ObjectUri))
                triple.ObjectId = ids[triple.ObjectUri];
        }
    }

    /// <summary>
    /// Adds to the set the implicit nodes, i.e. the nodes used by its
    /// triples which are neither in the set nor in the database.
    /// </summary>
    private static async Task AddImplicitNodesAsync(
        CadmusGraphDbContext context, GraphSet set, CancellationToken cancel)
    {
        HashSet<int> setIds = [.. set.Nodes.Select(n => n.Id)];
        Dictionary<int, UriNode> needed = [];

        void Need(int id, string? uri, UriTriple triple, bool predicate)
        {
            if (setIds.Contains(id)) return;
            if (needed.TryGetValue(id, out UriNode? node))
            {
                if (predicate) node.Tag = Node.TAG_PROPERTY;
                return;
            }
            needed[id] = new UriNode
            {
                Id = id,
                Uri = uri,
                Label = uri,
                Sid = triple.Sid,
                SourceType = Node.SOURCE_IMPLICIT,
                Tag = predicate ? Node.TAG_PROPERTY : null
            };
        }

        foreach (UriTriple triple in set.Triples)
        {
            Need(triple.SubjectId, triple.SubjectUri, triple, false);
            Need(triple.PredicateId, triple.PredicateUri, triple, true);
            if (triple.ObjectId != null)
                Need(triple.ObjectId.Value, triple.ObjectUri, triple, false);
        }
        if (needed.Count == 0) return;

        List<int> ids = [.. needed.Keys];
        HashSet<int> existing = [.. await context.Nodes.AsNoTracking()
            .Where(n => ids.Contains(n.Id))
            .Select(n => n.Id)
            .ToListAsync(cancel)];
        List<UriNode> missing = [.. needed.Values
            .Where(n => !existing.Contains(n.Id))];
        if (missing.Count == 0) return;

        // triples received with IDs only: get their URIs for labels
        List<int> noUri = [.. missing.Where(n => n.Uri == null)
            .Select(n => n.Id)];
        if (noUri.Count > 0)
        {
            Dictionary<int, string> uris = await context.UriEntries
                .AsNoTracking()
                .Where(u => noUri.Contains(u.Id))
                .ToDictionaryAsync(u => u.Id, u => u.Uri, cancel);
            foreach (UriNode node in missing.Where(n => n.Uri == null))
            {
                if (!uris.TryGetValue(node.Id, out string? uri))
                {
                    throw new CadmusGraphException(
                        $"Triple using an undefined node ID: {node.Id}");
                }
                node.Uri = node.Label = uri;
            }
        }

        foreach (UriNode node in missing)
        {
            node.Label = Truncate(node.Label, MAX_LABEL);
            set.Nodes.Add(node);
        }
    }

    private static bool CopyMappedNode(Node source, EfNode target)
    {
        bool changed = false;
        if (target.Label != source.Label)
        {
            target.Label = source.Label;
            changed = true;
        }
        if (target.Tag != source.Tag)
        {
            target.Tag = source.Tag;
            changed = true;
        }
        if (target.SourceType != source.SourceType)
        {
            target.SourceType = source.SourceType;
            changed = true;
        }
        if (target.Sid != source.Sid)
        {
            target.Sid = source.Sid;
            changed = true;
        }
        // mappings cannot define classes, so a class set by users is kept
        if (source.IsClass && !target.IsClass)
        {
            target.IsClass = true;
            changed = true;
        }
        return changed;
    }

    private static async Task UpdateSourceAsync(CadmusGraphDbContext context,
        string key, IList<UriNode> nodes, IList<UriTriple> triples,
        HashSet<int> preexisting, int aId, int subId, ClassChanges changes,
        CancellationToken cancel)
    {
        string prefix = key.ToLowerInvariant();

        // old set (tracked, as it gets updated)
        List<EfNode> oldNodes = await WhereSidStartsWith(context.Nodes, prefix)
            .ToListAsync(cancel);
        List<EfTriple> oldTriples = await WhereSidStartsWith(context.Triples,
            prefix).ToListAsync(cancel);

        // nodes: the same node may be emitted more than once
        Dictionary<int, UriNode> newNodes = [];
        foreach (UriNode node in nodes) newNodes.TryAdd(node.Id, node);

        Dictionary<int, EfNode> oldById = oldNodes.ToDictionary(n => n.Id);
        List<int> otherIds = [.. newNodes.Keys.Where(
            id => !oldById.ContainsKey(id) && preexisting.Contains(id))];
        Dictionary<int, EfNode> others = otherIds.Count == 0
            ? []
            : await context.Nodes.Where(n => otherIds.Contains(n.Id))
                .ToDictionaryAsync(n => n.Id, cancel);

        foreach (UriNode node in newNodes.Values)
        {
            if (oldById.TryGetValue(node.Id, out EfNode? old))
            {
                // already from this source: update it
                CopyMappedNode(node, old);
            }
            else if (others.TryGetValue(node.Id, out EfNode? other) &&
                other.SourceType == Node.SOURCE_IMPLICIT &&
                node.SourceType != Node.SOURCE_IMPLICIT)
            {
                // implicitly created by another source, and now explicitly
                // generated by this one: take its ownership
                CopyMappedNode(node, other);
            }
            // else either just added, or owned by another source or user
        }

        // triples
        Dictionary<TripleKey, EfTriple> oldByKey = [];
        List<EfTriple> deleted = [];
        foreach (EfTriple triple in oldTriples)
        {
            // duplicates may exist in databases written by older versions
            if (!oldByKey.TryAdd(GetKey(triple), triple)) deleted.Add(triple);
        }

        Dictionary<TripleKey, EfTriple> targets = [];
        foreach (UriTriple triple in triples)
        {
            TripleKey tk = GetKey(triple);
            if (targets.ContainsKey(tk)) continue;

            if (oldByKey.Remove(tk, out EfTriple? old))
            {
                // same triple: update its details
                CopyTripleDetails(triple, old);
                targets[tk] = old;
            }
            else
            {
                EfTriple added = CreateTriple(triple);
                context.Triples.Add(added);
                targets[tk] = added;
                changes.Add(triple, aId, subId);
            }
        }
        deleted.AddRange(oldByKey.Values);
        foreach (EfTriple triple in deleted) changes.Add(triple, aId, subId);
        context.Triples.RemoveRange(deleted);

        await context.SaveChangesAsync(cancel);

        // update the IDs of the received triples
        foreach (UriTriple triple in triples)
            triple.Id = targets[GetKey(triple)].Id;

        // nodes no longer generated from this source
        await ReleaseNodesAsync(context,
            [.. oldNodes.Where(n => !newNodes.ContainsKey(n.Id))],
            prefix, cancel);
    }

    /// <summary>
    /// Updates the graph with the specified nodes and triples. For each
    /// source represented in the set (by its nodes, triples, or
    /// <see cref="GraphSet.SourceIds"/>), the set replaces whatever was
    /// generated from it: new nodes and triples are added, changed ones
    /// updated, and those no longer generated are removed. Nodes no
    /// longer generated are kept when they are still used by any triple
    /// (see <see cref="DeleteGraphSetAsync"/>). Nodes created by users are
    /// never updated. The whole update is atomic, and concurrent updates
    /// of the same source are serialized.
    /// </summary>
    /// <param name="set">The new set of nodes and triples. The IDs of its
    /// nodes and triples are set by this method.</param>
    /// <param name="cancel">The cancellation token.</param>
    /// <exception cref="ArgumentNullException">set</exception>
    /// <exception cref="CadmusGraphException">invalid node or triple
    /// </exception>
    public async Task UpdateGraphAsync(GraphSet set,
        CancellationToken cancel = default)
    {
        ArgumentNullException.ThrowIfNull(set);

        // the sources being updated
        HashSet<string> sources = new(StringComparer.OrdinalIgnoreCase);
        foreach (string? sid in set.Nodes.Select(n => n.Sid)
            .Concat(set.Triples.Select(t => t.Sid))
            .Concat(set.SourceIds))
        {
            string key = GraphSet.GetSourceGuid(sid);
            if (key.Length > 0) sources.Add(key);
        }
        if (sources.Count == 0 && set.Nodes.Count == 0 &&
            set.Triples.Count == 0)
        {
            return;
        }

        await using CadmusGraphDbContext context = GetContext();
        await RunInTransactionAsync(context, async () =>
        {
            await LockAsync(context, LOCK_SOURCE, sources, cancel);

            await ResolveSetAsync(context, set, cancel);
            (int aId, int subId) = await GetASubIdsAsync(context, cancel);
            await AddImplicitNodesAsync(context, set, cancel);

            // insert all the missing nodes at once, in a consistent order
            List<int> nodeIds = [.. set.Nodes.Select(n => n.Id).Distinct()];
            HashSet<int> preexisting = [.. await context.Nodes.AsNoTracking()
                .Where(n => nodeIds.Contains(n.Id))
                .Select(n => n.Id)
                .ToListAsync(cancel)];
            await InsertMissingNodesAsync(context, [.. set.Nodes
                .Where(n => !preexisting.Contains(n.Id))
                .DistinctBy(n => n.Id)
                .OrderBy(n => n.Id)
                .Cast<Node>()], cancel);

            ClassChanges changes = new();
            IDictionary<string, IList<UriNode>> nodeGroups =
                set.GetNodesByGuid();
            IDictionary<string, IList<UriTriple>> tripleGroups =
                set.GetTriplesByGuid();

            foreach (string key in sources.Order(StringComparer.OrdinalIgnoreCase))
            {
                await UpdateSourceAsync(context, key,
                    nodeGroups.TryGetValue(key, out IList<UriNode>? n) ? n : [],
                    tripleGroups.TryGetValue(key, out IList<UriTriple>? t) ? t : [],
                    preexisting, aId, subId, changes, cancel);
            }

            // triples without SID (not generated by mappings): just ensure
            // that they exist
            if (tripleGroups.TryGetValue("", out IList<UriTriple>? userTriples))
            {
                foreach (UriTriple triple in userTriples)
                {
                    EfTriple? old = await FindTripleByValueAsync(triple,
                        context, cancel);
                    if (old != null)
                    {
                        triple.Id = old.Id;
                        continue;
                    }
                    EfTriple added = CreateTriple(triple);
                    context.Triples.Add(added);
                    await context.SaveChangesAsync(cancel);
                    triple.Id = added.Id;
                    changes.Add(triple, aId, subId);
                }
            }

            await UpdateClassesAsync(context, changes, aId, subId, cancel);
        }, cancel);
    }

    /// <summary>
    /// Updates the graph with the specified nodes and triples (see
    /// <see cref="UpdateGraphAsync"/>).
    /// </summary>
    /// <param name="set">The new set of nodes and triples.</param>
    /// <exception cref="ArgumentNullException">set</exception>
    public void UpdateGraph(GraphSet set) =>
        UpdateGraphAsync(set).GetAwaiter().GetResult();
    #endregion
}
